def set_rtl_font(run, font_name='Vazirmatn', size=11):
    """تنظیم فونت فارسی راست‌چین"""
    run.font.name = font_name
    run.font.size = Pt(size)
    rPr = run._element.get_or_add_rPr()
    rtl = OxmlElement('w:rtl')
    rPr.append(rtl)


def add_paragraph_rtl(doc, text, font_name='Vazirmatn', size=11, bold=False, color=None, alignment=WD_ALIGN_PARAGRAPH.RIGHT):
    """افزودن پاراگراف راست‌چین فارسی"""
    p = doc.add_paragraph()
    p.alignment = alignment
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run(text)
    run.font.name = font_name
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = color
    # تنظیم RTL
    pPr = p._element.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    pPr.append(bidi)
    return p


def add_heading_rtl(doc, text, level=1, color=None):
    """افزودن عنوان راست‌چین"""
    h = doc.add_heading('', level=level)
    h.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pPr = h._element.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    pPr.append(bidi)
    run = h.add_run(text)
    run.font.name = 'Vazirmatn'
    run.bold = True
    if color:
        run.font.color.rgb = color
    return h


def add_code_block(doc, code_text):
    """افزودن بلوک کد (LTR)"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing = 1.2
    run = p.add_run(code_text)
    run.font.name = 'Consolas'
    run.font.size = Pt(10)
    # پس‌زمینه خاکستری
    shading = OxmlElement('w:shd')
    shading.set(qn('w:val'), 'clear')
    shading.set(qn('w:color'), 'auto')
    shading.set(qn('w:fill'), 'F0F0F0')
    p.paragraph_format.paragraph_format = p.paragraph_format
    pPr = p._element.get_or_add_pPr()
    pPr.append(shading)
    return p


def add_table_data(doc, headers, rows):
    """افزودن جدول با داده‌ها"""
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Light Grid Accent 1'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    
    # هدر
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ''
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        run.font.name = 'Vazirmatn'
        run.font.size = Pt(10)
        run.bold = True
    
    # داده‌ها
    for r_idx, row_data in enumerate(rows, 1):
        for c_idx, val in enumerate(row_data):
            cell = table.rows[r_idx].cells[c_idx]
            cell.text = ''
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(str(val))
            run.font.name = 'Vazirmatn'
            run.font.size = Pt(10)
    return table


