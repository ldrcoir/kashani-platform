#!/usr/bin/env python3
"""
کد پایتون برای تأیید فاکتوریزاسیون M(1237)
==========================================
نکته مهم: F2 صحیح = M(1237) / F1
عددی که قبلاً به‌عنوان F2 داشتیم اشتباه بود!

نتیجه صحیح:
- M(1237) = F1 × F2
- F1 (70 رقم) اول ✓
- F2 (303 رقم) مرکب - هنوز فاکتور نشده!
- 109، 64237 فاکتورهای F2 نیستند!
"""

import gmpy2
from gmpy2 import mpz, is_prime

# ============================================================
#  محاسبه M(1237) و F1
# ============================================================
P = 1237
M_1237 = mpz(2)**P - 1

F1 = mpz("2538207129840687799335203259492870476186248896616401346500027311795983")

# F2 صحیح = M(1237) / F1
F2 = M_1237 // F1

# ============================================================
#  تأیید 1: F1 × F2 = M(1237)
# ============================================================
print("=" * 70)
print("  تأیید 1: F1 × F2 = M(1237)")
print("=" * 70)
print()

product = F1 * F2
print("F1 (70 رقم): " + str(F1)[:60] + "...")
print("F2 (303 رقم): " + str(F2)[:60] + "...")
print()
print("F1 × F2 ارقام: " + str(len(str(product))))
print("M(1237) ارقام: " + str(len(str(M_1237))))
print()
print("F1 × F2 (اولین 60 رقم): " + str(product)[:60] + "...")
print("M(1237)  (اولین 60 رقم): " + str(M_1237)[:60] + "...")
print()
print("F1 × F2 (آخرین 60 رقم): ..." + str(product)[-60:])
print("M(1237)  (آخرین 60 رقم): ..." + str(M_1237)[-60:])
print()
print("برابر؟ " + str(product == M_1237))
print()

# ============================================================
#  تأیید 2: F1 و F2 اول هستند؟
# ============================================================
print("=" * 70)
print("  تأیید 2: اول بودن فاکتورها")
print("=" * 70)
print()
print("F1 اول؟ " + str(is_prime(F1)))
print("F2 اول؟ " + str(is_prime(F2)))
print()

# ============================================================
#  تأیید 3: 109 و 64237 فاکتورهای F2 نیستند!
# ============================================================
print("=" * 70)
print("  تأیید 3: بررسی فاکتورهای قبلی")
print("=" * 70)
print()
print("F2 mod 109 = " + str(F2 % 109))
print("F2 mod 64237 = " + str(F2 % 64237))
print("F2 mod 7001833 = " + str(F2 % 7001833))
print()
print("نتیجه: 109 و 64237 فاکتورهای F2 صحیح نیستند!")
print()

# ============================================================
#  نمایش F2 صحیح کامل
# ============================================================
print("=" * 70)
print("  F2 صحیح (303 رقم)")
print("=" * 70)
print()
print(str(F2))
print()

# ============================================================
#  خلاصه
# ============================================================
print("=" * 70)
print("  خلاصه نهایی")
print("=" * 70)
print()
print("M(1237) = 2^1237 - 1")
print("       = F1 × F2")
print()
print("F1 = " + str(F1))
print("     (70 رقم، اول ✓)")
print()
print("F2 = " + str(F2)[:80] + "...")
print("     (303 رقم، مرکب - فاکتور نشده)")
print()
print("F1 × F2 = M(1237)؟ " + str(F1 * F2 == M_1237))
print()
print("⚠️  نتیجه:")
print("   F2 هنوز فاکتور نشده است!")
print("   109، 64237، 7001833 فاکتورهای F2 نیستند!")
print("   این فاکتورها برای عدد اشتباهی پیدا شده بودند.")
