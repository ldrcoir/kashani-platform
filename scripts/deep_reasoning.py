def lucas_v_mod(k, P_param, Q_param, N):
    """Compute V_k(P, Q) mod N using fast doubling."""
    if k == 0: return 2 % N
    if k == 1: return P_param % N
    # V_2n = V_n^2 - 2*Q^n
    # V_2n+1 = V_n * V_{n+1} - P * Q^n
    # Need to track Q^n
    # Use D = P^2 - 4Q (discriminant)
    # For Lucas with discriminant 5: P=1, Q=-1. D = 1 - 4*(-1) = 5.
    # V_0 = 2, V_1 = P = 1.
    # V_2n = V_n^2 - 2*Q^n = V_n^2 - 2*(-1)^n
    # V_2n+1 = V_n * V_{n+1} - P*Q^n = V_n * V_{n+1} - (-1)^n
    # 
    # Actually, let's track (V_n, V_{n+1}, Q^n) and use doubling.
    # With Q = -1, Q^n = (-1)^n which is just sign(n).
    
    bits = bin(k)[2:]
    # Track (V_n, V_{n+1}, sign) where sign = Q^n
    # Initial: n=0, V_0 = 2, V_1 = P, sign = 1
    a, b, sgn = mpz(2), mpz(P_param) % N, 1
    for bit in bits[1:]:
        # Double: (V_2n, V_2n+1, Q^2n)
        # V_2n = V_n^2 - 2*Q^n = a^2 - 2*sgn
        # V_2n+1 = V_n * V_{n+1} - P*Q^n = a*b - P*sgn
        # Q^2n = sgn^2 = 1 (since Q = -1)
        c = (a*a - 2*sgn) % N  # V_2n
        d = (a*b - P_param*sgn) % N  # V_2n+1
        new_sgn = 1  # Q^2n = 1
        if bit == '0':
            a, b, sgn = c, d, new_sgn
        else:
            # Advance by 1: (V_2n+1, V_2n+2, Q^(2n+1))
            # V_2n+2 = V_2n+1 * P - Q * V_2n = d * P - (-1) * c = d*P + c
            # Or use: V_2n+2 = V_{n+1}^2 - 2*Q^(n+1) = b^2 - 2*sgn*Q
            # With Q = -1: V_2n+2 = b^2 - 2*(-1)*sgn = b^2 + 2*sgn
            e = (b*b - 2*sgn*Q_param) % N  # V_2n+2 = b^2 - 2*Q^(n+1)
            # Q^(2n+1) = Q^2n * Q = 1 * Q = -1 = sgn * Q (since sgn was Q^n before doubling... wait, after doubling sgn = Q^2n = 1)
            # Actually let me be more careful.
            # After doubling, we have (V_2n, V_2n+1, Q^2n). 
            # To advance: (V_2n+1, V_2n+2, Q^(2n+1)) = (d, e, Q^2n * Q)
            new_sgn_adv = (new_sgn * Q_param) % N  # = -1 * 1 = -1 → as mod: N-1
            a, b, sgn = d, e, new_sgn_adv
    return int(a)

