digit_sum = sum(int(d) for d in N_str)
log(f'  مجموع ارقام: {digit_sum}')

# C303 mod 9 = مجموع ارقام mod 9
log(f'  C303 mod 9 = {N % 9} = digit_sum mod 9 = {digit_sum % 9}')

# الگوی تکرار در رقم‌ها
# مثلاً آیا "123" یا "456" تکرار می‌شود؟
log(f'  پرتکرارترین 3-grams در C303:')
three_grams = Counter()
for i in range(len(N_str) - 2):
    three_grams[N_str[i:i+3]] += 1
for g, c in three_grams.most_common(10):
    log(f'    "{g}": {c}')

