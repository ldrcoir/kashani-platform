def lucas_v_1237(k, mod):
    """Compute V_k(1237, 1) mod `mod` using fast doubling."""
    if k == 0: return 2 % mod
    if k == 1: return 1237 % mod
    
    P_param = 1237
    Q_param = 1
    
    bits = bin(k)[2:]
    # (V_n, V_{n+1}, Q^n)
    a, b, qn = mpz(2), mpz(P_param) % mod, mpz(1)
    
    for bit in bits:
        # Doubling: V_2n = V_n^2 - 2*Q^n, V_2n+1 = V_n*V_{n+1} - P*Q^n
        c = (a*a - 2*qn) % mod
        d = (a*b - P_param*qn) % mod
        new_qn = (qn*qn) % mod
        if bit == '0':
            a, b, qn = c, d, new_qn
        else:
            # Advance by 1: V_2n+2 = V_{n+1}^2 - 2*Q^(n+1) = b^2 - 2*new_qn*Q
            e = (b*b - 2*new_qn*Q_param) % mod
            new_qn_adv = (new_qn * Q_param) % mod
            a, b, qn = d, e, new_qn_adv
    
    return int(a)

