if (N - 1) & (N - 2) == 0 and N > 1:
    log(f'  C303 = 2^k + 1 است')
else:
    log(f'  C303 ≠ 2^k + 1')

# C303 را در فرم 2^a * 3^b * 5^c * ... بنویسیم (آیا ممکن است؟)
n_temp = N
structure = []
for p in [2, 3, 5, 7, 11, 13]:
    while n_temp % p == 0:
        structure.append(p)
        n_temp //= p
log(f'  عوامل کوچک C303: {structure} (همه‌ی آن‌ها خالی هستند چون C303 فرد و بر 3 بخش‌پذیر نیست)')
