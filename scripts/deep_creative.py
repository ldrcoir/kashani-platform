log(f'  تعداد 1: {N_bin.count("1")}, تعداد 0: {N_bin.count("0")}')

# آیا C303 به‌فرم 2^k ± 1 است؟ (عدد مرسن یا فرما)
if (N & (N - 1)) == 0:
    log(f'  C303 توان ۲ است!')
else:
    log(f'  C303 توان ۲ نیست')

