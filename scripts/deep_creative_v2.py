# ولی می‌توانیم بسط لگاریتم طبیعی را به‌صورت سری در نظر بگیریم:
# ln(C303) = ln(2^1237 - 1) - ln(P70) = ln(2^1237) + ln(1 - 2^(-1237)) - ln(P70)
#           = 1237 * ln(2) + ln(1 - 2^(-1237)) - ln(P70)
#           ≈ 1237 * ln(2) - ln(P70) (چون 2^(-1237) بسیار کوچک)

ln_C303 = math.log(N)
ln_P70 = math.log(int(P70))
ln_2 = math.log(2)
approx_ln_C303 = 1237 * ln_2 - ln_P70
log(f'  ln(C303) = {ln_C303}')
log(f'  تقریب: 1237 * ln(2) - ln(P70) = {approx_ln_C303}')
log(f'  تفاوت (به‌دلیل 2^(-1237)): {ln_C303 - approx_ln_C303} (بسیار نزدیک به صفر)')
