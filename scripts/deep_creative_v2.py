log(f'  میانگین رقم: {digit_mean:.2f}')

# واریانس
var = sum((int(d) - digit_mean) ** 2 for d in N_str) / n
log(f'  واریانس: {var:.2f}')

# انحراف معیار
std = var ** 0.5
log(f'  انحراف معیار: {std:.2f}')

# آیا توزیع ارقام یکنواخت است؟
expected = n / 10
from collections import Counter as Cnt2
digit_counts_local = Cnt2(N_str)
chi_sq = sum((digit_counts_local[d] - expected) ** 2 / expected for d in digit_counts_local)
log(f'  Chi-squared توزیع ارقام: {chi_sq:.2f} (با df=9، انتظار ~9)')
log(f'  اگر chi-squared > 16.92 (95% CI)، توزیع یکنواخت نیست')

log(f'')

# ============================================================
# روش ۱۰: کشف ساختار پنهان با تبدیل Fourier
# ============================================================
log(f'=== روش ۱۰: تحلیل Fourier رقم‌های C303 ===')
log(f'')

# ارقام C303 به‌صورت یک سیگنال
import cmath
digits = [int(d) for d in N_str]

# محاسبه‌ی DFT
n = len(digits)
log(f'  طول سیگنال: {n}')
# محاسبه‌ی DFT کوتاه (64 نقطه)
N_FFT = 64
if n > N_FFT:
    # میانگین‌گیری در بلوک‌های n/N_FFT
    block_size = n // N_FFT
    signal = []
    for i in range(N_FFT):
        block = digits[i*block_size:(i+1)*block_size]
        signal.append(sum(block) / len(block))
else:
    signal = digits[:N_FFT] + [0] * (N_FFT - len(digits))

# DFT
dft = []
for k in range(N_FFT):
    s = 0
    for j in range(N_FFT):
        s += signal[j] * cmath.exp(-2j * cmath.pi * 1j * k * j / N_FFT)
    dft.append(s)

# پیدا کردن فرکانس‌های غالب
magnitudes = [abs(dft[k]) for k in range(N_FFT // 2)]
top_freqs = sorted(range(len(magnitudes)), key=lambda i: -magnitudes[i])[:5]
log(f'  ۵ فرکانس غالب در DFT ارقام:')
for f in top_freqs:
    log(f'    freq {f}: magnitude {magnitudes[f]:.2f}')

log(f'')

