# اگر p ≈ q (سناریوی «متوازن»):
# هر دو ≈ 10^151.5
# یعنی k ≈ 10^151.5 / 2474 ≈ 10^148

# اگر p << q (سناریوی «نامتوازن»):
# مثلاً p ≈ 10^80، q ≈ 10^223
# یعنی k_p ≈ 4 * 10^76

# تخمین با Dickman:
# احتمال اینکه فاکتور کوچک‌تر p ≤ 10^D باشد:
# P(p ≤ 10^D | C303 = p*q با p ≤ q) = 1 - log_10^D / log_10^(N/2)
#                                       = 1 - D / 151.5
# (این فرمول تقریبی Dickman است)

log(f'  تخمین احتمال اندازه‌ی فاکتور کوچک‌تر (با Dickman):')
