# احتمال قبلی (prior): فاکتور با توزیع Dickman
# اطلاعات جدید: smart sieve تا k = 10^14 هیچ فاکتور پیدا نکرد
# احتمال پسین (posterior): P(p > 10^15 | data)

# با فرض Dickman: 
# اگر p ∈ [10^15, 10^151.5] با توزیع Dickman
# P(p ≤ 10^14 | Dickman) = (1 - 14/151.5) = 0.908
# P(p > 10^14 | Dickman) = 0.092
# پس: عدم یافتن فاکتور در k < 10^14 این احتمال را می‌رساند: 0.092 (که درست است)

# احتمال پسین:
# P(p ≤ 10^D | no factor in [10^0, 10^14]) = P(p ≤ 10^D, p > 10^14) / P(p > 10^14)
# = (1 - D/151.5 - 0.092) / 0.092 (اگر D ≥ 14)
# = (1 - 14/151.5 - 0.092) / 0.092 = 0

# به‌عبارت دیگر:
# اگر Dickman درست باشد و ما فاکتور در k < 10^14 پیدا نکرده‌ایم:
# احتمال اینکه p ≤ 10^14 باشد: صفر (تأیید شده)
# احتمال اینکه p > 10^14 باشد: 100%

# حالا با ECM با B1=10^10 (که فاکتورهای 50 رقمی را پیدا می‌کند):
# احتمال p ≤ 10^50 با Dickman: 1 - 50/151.5 = 0.670
# ولی ECM پیدا نکرد → احتمال «پیدا نکردن» = 1 - 0.670 = 0.330 (با فرض p < 50)
# پس:
# P(p ≤ 10^50 | smart sieve + ECM) = P(no factor in [10^0, 10^14]) × P(no factor in [10^14, 10^50])
#                                 = (1 - 14/151.5) × (no detection in 50-14 = 36 in 151.5-14 = 137.5)
#                                 = 0.908 × (1 - 36/137.5)
#                                 = 0.908 × 0.738
#                                 = 0.670 (تقریبی)

# پس احتمال اینکه فاکتور > 50 رقم باشد:
