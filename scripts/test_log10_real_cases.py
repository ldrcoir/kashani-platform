#!/usr/bin/env python3
"""
Real test of the log10 trick on a known composite.

The CORRECT interpretation of the user's request:
- Build a composite number N = p1 × p2 (or similar) where p1, p2 are known primes.
- Apply the log10 trick:
  - Generate primes whose log10 sum approaches log10(N).
  - Check if any of them (or their product) shares a factor with N.
- Show whether the technique actually finds a factor.

We'll try 3 cases:
1. N = small_prime × big_prime (asymmetric) — trick should work via trial-division-like coverage.
2. N = medium_prime × medium_prime (similar sizes) — trick should fail.
3. N = 3 primes of various sizes — partial coverage.

For each, we'll show:
- The actual factorization
- log10(N)
- The primes generated by the log10 trick
- Whether gcd(product_of_primes, N) > 1
"""

import sys
sys.set_int_max_str_digits(1000000)

import gmpy2
from gmpy2 import mpz, is_prime, next_prime, gcd
import math
import time
import random
from pathlib import Path

print("=" * 70)
print("  تست واقعی تکنیک log10 روی اعداد مرکب شناخته‌شده")
print("=" * 70)
print()

random.seed(42)
def random_prime_with_digits(d):
    low = 10**(d-1)
    high = 10**d - 1
    while True:
        n = random.randint(low, high)
        if n % 2 == 0: n += 1
        p = int(next_prime(mpz(n)))
        if p <= high: return p

def small_primes_up_to(limit):
    sieve = bytearray([1]) * (limit + 1)
    sieve[0] = sieve[1] = 0
    for i in range(2, int(limit**0.5) + 1):
        if sieve[i]:
            sieve[i*i::i] = b'\x00' * len(sieve[i*i::i])
    return [i for i in range(2, limit + 1) if sieve[i]]

# ============================================================
# Case 1: ASYMMETRIC — small factor × large factor
# ============================================================
print("=" * 70)
print("  حالت ۱: عدد مرکب با فاکتور کوچک و بزرگ (نامتقارن)")
print("=" * 70)
print()

p1 = random_prime_with_digits(7)   # small 7-digit
p2 = random_prime_with_digits(40)  # big 40-digit
N1 = p1 * p2
log10_N1 = math.log10(N1)
print(f"p1 = {p1} (7 digits)")
print(f"p2 = {p2} (40 digits)")
print(f"N1 = p1 × p2 = {str(N1)[:60]}... ({len(str(N1))} digits)")
print(f"log10(N1) = {log10_N1:.10f}")
print()

# Apply log10 trick: greedy ascending (use primes 2, 3, 5, ... up to some bound)
# Strategy: include ALL primes up to 10^7 (which includes p1 since p1 is 7-digit)
print("استراتژی: primorial(10^7) — همه‌ی اعداد اول تا 10^7")
primes_pool = small_primes_up_to(10**7)
print(f"  تولید {len(primes_pool)} عدد اول")
print()

# Greedy ascending to approach log10(N1)
selected = []
sum_log = 0.0
for p in primes_pool:
    lp = math.log10(p)
    if sum_log + lp <= log10_N1 + 1e-9:  # tiny tolerance
        selected.append(p)
        sum_log += lp

print(f"تعداد انتخاب‌شده: {len(selected)} عدد")
print(f"بزرگ‌ترین عدد اول انتخاب‌شده: {selected[-1]}")
print(f"جمع log10 = {sum_log:.10f}")
print(f"هدف log10 = {log10_N1:.10f}")
print(f"خطا = {log10_N1 - sum_log:.10e}")
print()

# Now the KEY question: does any of these selected primes divide N1?
print("بررسی: آیا هر کدام از اعداد انتخاب‌شده فاکتور N1 هستند؟")
print(f"  (نکته: p1 = {p1} در selected هست؟ {p1 in selected})")

# Compute product and gcd
product = mpz(1)
for p in selected:
    product *= mpz(p)

g = gcd(int(product), int(N1))
print(f"  gcd(∏ selected, N1) = {g}")
if g > 1 and g < N1:
    print(f"  ✓✓✓ فاکتور پیدا شد: {g}")
    print(f"  is_prime: {is_prime(g)}")
    cof = N1 // g
    print(f"  cofactor = {cof}, is_prime: {is_prime(cof)}")
    if g == p1:
        print(f"  ✓ این p1 (عامل کوچک) بود!")
    elif g == p2:
        print(f"  ✓ این p2 (عامل بزرگ) بود!")
else:
    print(f"  ✗ فاکتور پیدا نشد")
    if p1 in selected:
        print(f"  عجیب! p1 در selected بود ولی gcd کار نکرد؟")
print()

# ============================================================
# Case 2: SYMMETRIC — two primes of similar size
# ============================================================
print("=" * 70)
print("  حالت ۲: عدد مرکب با دو فاکتور متوسط (متقارن)")
print("=" * 70)
print()

p1 = random_prime_with_digits(30)
p2 = random_prime_with_digits(30)
N2 = p1 * p2
log10_N2 = math.log10(N2)
print(f"p1 = {p1} (30 digits)")
print(f"p2 = {p2} (30 digits)")
print(f"N2 = p1 × p2 = {str(N2)[:60]}... ({len(str(N2))} digits)")
print(f"log10(N2) = {log10_N2:.10f}")
print()

# Apply log10 trick
print("استراتژی: primorial(10^7) — همه‌ی اعداد اول تا 10^7")
selected = []
sum_log = 0.0
for p in primes_pool:
    lp = math.log10(p)
    if sum_log + lp <= log10_N2 + 1e-9:
        selected.append(p)
        sum_log += lp

print(f"تعداد انتخاب‌شده: {len(selected)}")
print(f"بزرگ‌ترین انتخاب‌شده: {selected[-1]}")
print(f"جمع log10 = {sum_log:.10f}, هدف = {log10_N2:.10f}")
print(f"خطا = {log10_N2 - sum_log:.10e}")
print()

print("بررسی: آیا هر کدام فاکتور N2 هستند؟")
print(f"  p1 = {p1} در selected هست؟ {p1 in selected}")
print(f"  p2 = {p2} در selected هست؟ {p2 in selected}")

product = mpz(1)
for p in selected:
    product *= mpz(p)
g = gcd(int(product), int(N2))
print(f"  gcd(∏ selected, N2) = {g}")
if g > 1 and g < N2:
    print(f"  ✓ فاکتور: {g}")
else:
    print(f"  ✗ فاکتور پیدا نشد (دقیقاً همان وضعیت F2)")
print()

# ============================================================
# Case 3: Three primes, one small
# ============================================================
print("=" * 70)
print("  حالت ۳: عدد مرکب با سه فاکتور، یکی کوچک")
print("=" * 70)
print()

p1 = random_prime_with_digits(5)   # 5-digit small
p2 = random_prime_with_digits(15)  # 15-digit medium
p3 = random_prime_with_digits(25)  # 25-digit large
N3 = p1 * p2 * p3
log10_N3 = math.log10(N3)
print(f"p1 = {p1} (5 digits)")
print(f"p2 = {p2} (15 digits)")
print(f"p3 = {p3} (25 digits)")
print(f"N3 = p1 × p2 × p3 = {str(N3)[:60]}... ({len(str(N3))} digits)")
print(f"log10(N3) = {log10_N3:.10f}")
print()

selected = []
sum_log = 0.0
for p in primes_pool:
    lp = math.log10(p)
    if sum_log + lp <= log10_N3 + 1e-9:
        selected.append(p)
        sum_log += lp

print(f"استراتژی primorial(10^7): {len(selected)} عدد انتخاب‌شده")
print(f"بزرگ‌ترین: {selected[-1]}")
print(f"جمع log10 = {sum_log:.10f}, هدف = {log10_N3:.10f}")
print(f"خطا = {log10_N3 - sum_log:.10e}")
print()

print(f"بررسی: p1 در selected؟ {p1 in selected}")
print(f"بررسی: p2 در selected؟ {p2 in selected}")
print(f"بررسی: p3 در selected؟ {p3 in selected}")

product = mpz(1)
for p in selected:
    product *= mpz(p)
g = gcd(int(product), int(N3))
print(f"gcd(∏ selected, N3) = {g}")
if g > 1 and g < N3:
    print(f"  ✓✓✓ فاکتور پیدا شد: {g}")
    print(f"  is_prime: {is_prime(g)}")
    cof = N3 // g
    print(f"  cofactor = {cof} ({len(str(cof))} digits)")
    print(f"  is_prime(cofactor): {is_prime(cof)}")
    # Check if all 3 primes are covered
    if g == p1:
        print(f"  ✓ p1 پیدا شد!")
        # Check cofactor
        if cof == p2 * p3:
            print(f"  ✓ cofactor = p2 × p3 (کامل)!")
    # Also check if g includes p2 also (if p2 in selected too)
    if g % p2 == 0:
        print(f"  ✓ p2 هم در gcd هست!")
        if g == p1 * p2:
            print(f"  ✓ g = p1 × p2")
else:
    print(f"  ✗ فاکتور پیدا نشد")
print()

