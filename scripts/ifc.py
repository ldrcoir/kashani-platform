    residue_map = {1: 3, 2: 5, 3: 7}  # k_mod_4 → q_mod_8
    
    for r_class in [1, 2, 3]:  # skip 0 (q ≡ 1 mod 8)
        q_mod_8 = residue_map[r_class]
        log(f'  Scanning k ≡ {r_class} mod 4 (gives q ≡ {q_mod_8} mod 8)...')
        t0 = time.time()
        count = 0
        for k in range(r_class, 100_000_001, 4):
            q_cand = 2 * k * p + 1
            if not is_prime(q_cand):
                continue
            if powmod(2, p, q_cand) == 1:
                log(f'  >>> k={k}: q={q_cand} is a factor of M({p})!')
                update_factor_file(p, int(q_cand))
                cofactor = int(M) // int(q_cand)
                append_complete(p, int(q_cand), cofactor)
                return
            count += 1
            if count % 500_000 == 0:
                elapsed = time.time() - t0
                if elapsed > 25:
                    log(f'    k={k}, count={count}, elapsed={elapsed:.1f}s')
                    break
        elapsed = time.time() - t0
        log(f'    Done k ≡ {r_class} mod 4, k up to {k}, count={count}, time={elapsed:.1f}s')
    
    log('')
    log('No factor found via IFC')


