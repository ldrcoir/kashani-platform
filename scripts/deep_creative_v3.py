# C303 ≡ 0 (mod p)
# C303 ≡ 0 (mod q)
# ولی C303 ≡ some_value (mod small_primes)
# با استفاده از CRT: (p, q) ≡ (something, something) (mod m) برای هر m

# مثال: برای m = 90، C303 ≡ 7 (mod 90)
