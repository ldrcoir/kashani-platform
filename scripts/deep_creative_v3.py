# حالا: 74 و 360 چه رابطه‌ای دارند؟
log(f'  gcd(74, 360) = {gcd(74, 360)}')
# gcd = 2، پس 74*x + 1 می‌تواند همه‌ی مقادیر فرد را به خود بگیرد
# ولی 74*x + 1 = odd iff 74*x is even iff x is anything (74 = 2 * 37, 74*x همیشه زوج)
# پس p همیشه فرد (خوب)

# کره‌ی 360 = 2^3 * 3^2 * 5
# (74*k + 1) mod 8: 74 = 2*37، 74*k mod 8 = 2*k mod 8
# پس 74*k + 1 mod 8 = (2k + 1) mod 8 = 1, 3, 5, 7 (همه‌ی فرد)

# تجزیه‌ی معادله:
# برای هر k_p mod 360، (74*k_p + 1) mod 360 چه می‌شود؟
# 74 * 360 = 26640 ≡ 0 (mod 360)، پس دوره‌ی 360 است
# 74 mod 360 = 74، 74*2 = 148، 74*3 = 222، 74*4 = 296، 74*5 = 370 ≡ 10
# پس 74*k + 1 به صورت (74*k mod 360) + 1 = (74*k_p mod 360) + 1

# پیدا کردن همه‌ی (k_p mod 360, k_q mod 360) که معادله را حل می‌کنند
solutions_360 = []
for k_p_mod in range(360):
    p_mod = (74 * k_p_mod + 1) % 360
    # (p_mod) * (74*k_q + 1) ≡ 97 (mod 360)
    # 74*k_q + 1 ≡ 97 * inverse(p_mod, 360) (mod 360) (اگر inverse وجود داشته باشد)
    g = gcd(p_mod, 360)
    if g != 1:
        continue
    inv = int(invert(p_mod, 360))
    q_target = (97 * inv) % 360
    # 74*k_q + 1 ≡ q_target (mod 360)
    # 74*k_q ≡ q_target - 1 (mod 360)
    if (q_target - 1) % g != 0:
        continue  # باید بخش‌پذیر باشد
    # k_q ≡ (q_target - 1) / 74 (mod 360/gcd(74,360))
    # 74 = 2*37، 360 = 2^3*3^2*5، gcd(74, 360) = 2
    # 74*k_q ≡ (q_target - 1) (mod 360)
    # اگر (q_target - 1) زوج باشد، می‌توان حل کرد
    if (q_target - 1) % 2 != 0:
        continue
    # تقسیم بر 2: 37*k_q ≡ (q_target - 1)/2 (mod 180)
    half_q = (q_target - 1) // 2
    # حالا 37*k_q ≡ half_q (mod 180)
    # gcd(37, 180) = 1 (37 اول و 180 = 4*45 = 4*9*5)
    inv_37 = int(invert(37, 180))
    k_q_mod = (half_q * inv_37) % 180
    # k_q mod 180, ولی ما k_q mod 360 لازم داریم
    # پس k_q ∈ {k_q_mod, k_q_mod + 180} (mod 360)
    solutions_360.append((k_p_mod, k_q_mod))
    solutions_360.append((k_p_mod, k_q_mod + 180))

