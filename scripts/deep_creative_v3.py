# برای هر k_p: p mod 90 = (44 * k_p + 1) mod 90
# برای هر k_q: q mod 90 = (44 * k_q + 1) mod 90
# محصول: ((44*k_p + 1) * (44*k_q + 1)) mod 90 = 7

# این یک معادله‌ی Diophantine برای k_p و k_q است
# می‌توانیم برای k_p های کوچک، k_q را پیدا کنیم

log(f'  قید mod 90 با ساختار Mersenne (p = 2474*k_p + 1، q = 2474*k_q + 1):')
log(f'  (44*k_p + 1) * (44*k_q + 1) ≡ 7 (mod 90)')

# نمونه: k_p = 0 → p = 1 (نه اول)
# k_p = 1 → p = 2475 (not prime, divisible by 3)
# k_p = 2 → p = 4949 (prime?)
# برای k_p های کوچک، بررسی ک
found_solutions = []
for k_p_mod in range(90):
    p_mod = (44 * k_p_mod + 1) % 90
    # (p_mod) * (44*k_q + 1) ≡ 7 (mod 90)
    # (44*k_q + 1) ≡ 7 * inverse(p_mod, 90) (mod 90) (اگر inverse وجود داشته باشد)
    if gcd(p_mod, 90) != 1:
        # p_mod و 90 باید coprime باشند
        continue
    inv = int(invert(p_mod, 90))
    q_target = (7 * inv) % 90
    # 44*k_q + 1 ≡ q_target (mod 90)
    # 44*k_q ≡ q_target - 1 (mod 90)
    # k_q ≡ (q_target - 1) * inverse(44, 90) (mod 90) (اگر inverse وجود داشته باشد)
    if gcd(44, 90) != 1:
        continue
    inv_44 = int(invert(44, 90))
    k_q_mod = ((q_target - 1) * inv_44) % 90
    found_solutions.append((k_p_mod, k_q_mod))

